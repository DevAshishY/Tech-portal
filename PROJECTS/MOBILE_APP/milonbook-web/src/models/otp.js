import mongoose from "mongoose";

const OTPSchema = new mongoose.Schema({
  email: {
    type: String,
    required: true,
  },
  otp: {
    type: String,
    required: true,
  },
  expiresAt: {
    type: Date,
    required: true,
  },
});

// Prevent model overwrite issues in dev
export default mongoose.models.OTP || mongoose.model("OTP", OTPSchema);
